const NAMES = new Set(Object.values(COUNTRIES));

const normalize = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .toUpperCase()
    .replace(/[^A-Z]+/g, "_")
    .replace(/^_|_$/g, "");

/** Accepts an ISO code ("co", "CO"), the enum value ("COLOMBIA") or its plain name ("Colombia", "costa rica"). */
export function toCountryName(input: string): string {
  const iso = COUNTRIES[input.trim().toLowerCase()];
  if (iso) return iso;
  const name = normalize(input);
  if (NAMES.has(name)) return name;
  throw new CliError(
    `País desconocido: "${input}". Usa el código de 2 letras (CO, BR, MX…) o el nombre en inglés (COLOMBIA, BRAZIL, MEXICO…).`,
  );
}
